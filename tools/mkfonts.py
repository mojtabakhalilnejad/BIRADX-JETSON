#!/usr/bin/env python3
"""Rasterise the interface fonts into C++ arrays (4-bit coverage, 2 px/byte).

    python3 tools/mkfonts.py   ->  fonts/fonts_data.cpp

Inter (OFL) for text, JetBrains Mono (OFL) for numbers and ids, DejaVu Sans for
the few symbols those two lack. The Jetson's Theme.qml asks for exactly these
families ("Inter, Roboto, ..." and "JetBrains Mono, ..."). Sizes are pixel
sizes, as QML's font.pixelSize.
"""
import os, sys
import freetype

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'fonts', 'src')
OUT = os.path.join(HERE, '..', 'fonts', 'fonts_data.cpp')

ASCII = list(range(32, 127))
EXTRA = [0xB0, 0xB7, 0xB1, 0xD7, 0xB5, 0x2013, 0x2014, 0x2022, 0x2026, 0x2190, 0x2191,
         0x2192, 0x2193, 0x2264, 0x2265, 0x3A9, 0x2713, 0x2715, 0x22EF, 0x25CF, 0x2699, 0x221A, 0x2212, 0x21BA, 0x21BB]
DIGITS = [ord(c) for c in "0123456789 +-.,:%?"] + [0x2014, 0x2212]

# name, file, weight, pixel size, charset
FONTS = [
    ('S10',  'Inter.ttf', 400, 10, 'all'),
    ('S11',  'Inter.ttf', 400, 11, 'all'),
    ('S12',  'Inter.ttf', 400, 12, 'all'),
    ('S13',  'Inter.ttf', 400, 13, 'all'),
    ('S14',  'Inter.ttf', 400, 14, 'all'),
    ('S16',  'Inter.ttf', 400, 16, 'all'),
    ('S19',  'Inter.ttf', 400, 19, 'all'),
    ('SB11', 'Inter.ttf', 700, 11, 'all'),
    ('SB12', 'Inter.ttf', 650, 12, 'all'),
    ('SB14', 'Inter.ttf', 650, 14, 'all'),
    ('SB16', 'Inter.ttf', 700, 16, 'all'),
    ('SB19', 'Inter.ttf', 700, 19, 'all'),
    ('SB24', 'Inter.ttf', 700, 24, 'all'),
    ('SB29', 'Inter.ttf', 700, 29, 'all'),
    ('SB36', 'Inter.ttf', 700, 36, 'all'),
    ('M9',   'JetBrainsMono.ttf', 400, 9, 'all'),
    ('M10',  'JetBrainsMono.ttf', 400, 10, 'all'),
    ('M11',  'JetBrainsMono.ttf', 400, 11, 'all'),
    ('M12',  'JetBrainsMono.ttf', 400, 12, 'all'),
    ('M14',  'JetBrainsMono.ttf', 400, 14, 'all'),
    ('MB9',  'JetBrainsMono.ttf', 700, 9, 'all'),
    ('MB10', 'JetBrainsMono.ttf', 700, 10, 'all'),
    ('MB14', 'JetBrainsMono.ttf', 650, 14, 'all'),
    ('MB19', 'JetBrainsMono.ttf', 650, 19, 'all'),
    ('MB24', 'JetBrainsMono.ttf', 400, 24, 'all'),
    ('MB44', 'JetBrainsMono.ttf', 700, 44, 'all'),
    ('MB46', 'JetBrainsMono.ttf', 400, 46, 'digits'),
    ('MB64', 'JetBrainsMono.ttf', 700, 64, 'digits'),
]


def face(fn, weight):
    f = freetype.Face(os.path.join(SRC, fn))
    try:
        axes = f.get_variation_info().axes
        coords = []
        for a in axes:
            if a.tag == 'wght': coords.append(weight)
            elif a.tag == 'opsz': coords.append(min(max(14.0, a.default), 32.0))
            else: coords.append(a.default)
        f.set_var_design_coords(coords)
    except Exception:
        pass
    return f


def render(name, fn, weight, px, cs):
    main = face(fn, weight)
    fb = face('DejaVuSans-Bold.ttf' if weight >= 600 else 'DejaVuSans.ttf', weight)
    for f in (main, fb):
        f.set_pixel_sizes(0, px)
    cps = sorted(set((ASCII + EXTRA) if cs == 'all' else DIGITS))
    glyphs, bits = [], bytearray()
    asc = main.size.ascender >> 6
    desc = -(main.size.descender >> 6)
    lh = main.size.height >> 6
    for cp in cps:
        f = main if main.get_char_index(cp) else (fb if fb.get_char_index(cp) else None)
        if f is None:
            continue
        f.load_char(chr(cp), freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_LIGHT)
        g = f.glyph
        b = g.bitmap
        w, h = b.width, b.rows
        adv = (g.advance.x + 32) >> 6
        off = len(bits)
        rowbytes = (w + 1) // 2
        buf = b.buffer
        for y in range(h):
            row = bytearray(rowbytes)
            for x in range(w):
                v = buf[y * b.pitch + x] >> 4
                if x & 1: row[x >> 1] |= v
                else: row[x >> 1] |= v << 4
            bits += row
        glyphs.append((cp, g.bitmap_left, g.bitmap_top, w, h, adv, off))
    return dict(name=name, px=px, asc=asc, desc=desc, lh=lh, glyphs=glyphs, bits=bits)


def main():
    fonts = [render(*f) for f in FONTS]
    o = []
    o.append('// GENERATED by tools/mkfonts.py — do not edit.\n'
             '// Inter and JetBrains Mono are under the SIL Open Font License 1.1\n'
             '// (fonts/src/OFL-*.txt); DejaVu Sans glyphs are under the Bitstream Vera licence.\n'
             '#include "fonts.h"\n\nnamespace fonts {\n')
    total = 0
    for f in fonts:
        n = f['name']
        o.append('static const uint8_t %s_bits[%d] = {' % (n, max(1, len(f['bits']))))
        bb = f['bits'] or b'\x00'
        for i in range(0, len(bb), 32):
            o.append('\n  ' + ','.join(str(x) for x in bb[i:i+32]) + ',')
        o.append('\n};\n')
        o.append('static const Glyph %s_glyphs[%d] = {\n' % (n, len(f['glyphs'])))
        for (cp, l, t, w, h, adv, off) in f['glyphs']:
            o.append('  {0x%04X,%d,%d,%d,%d,%d,%d},\n' % (cp, l, t, w, h, adv, off))
        o.append('};\n')
        o.append('const Font %s = { %d, %d, %d, %d, %d, %s_glyphs, %s_bits };\n\n' % (
            n, f['px'], f['asc'], f['desc'], f['lh'], len(f['glyphs']), n, n))
        total += len(f['bits']) + len(f['glyphs']) * 12
    o.append('} // namespace fonts\n')
    open(OUT, 'w').write(''.join(o))
    hdr = os.path.join(HERE, '..', 'fonts', 'fonts_list.h')
    open(hdr, 'w').write('// GENERATED by tools/mkfonts.py\nnamespace fonts {\n' +
                         ''.join('extern const Font %s;\n' % f['name'] for f in fonts) + '}\n')
    print('fonts: %d faces, %.0f kB' % (len(fonts), total / 1024.0))


if __name__ == '__main__':
    main()
