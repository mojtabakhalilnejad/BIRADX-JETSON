#!/usr/bin/env python3
# tools/mklogo.py — the start-screen logo (assets/coosa_full.svg) as an 8-bit
# coverage mask, drawn white on black by gui/splash.cpp.
import io, os, cairosvg
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
W = 380
svg = open(os.path.join(HERE, '..', 'assets', 'coosa_full.svg')).read().replace('#F2F6F8', '#FFFFFF')
png = cairosvg.svg2png(bytestring=svg.encode(), output_width=W, background_color='black')
im = Image.open(io.BytesIO(png)).convert('L')
w, h = im.size
px = im.tobytes()
with open(os.path.join(HERE, '..', 'gui', 'logo_data.cpp'), 'w') as f:
    f.write('// Generated by tools/mklogo.py from assets/coosa_full.svg. Do not edit.\n')
    f.write('#include "splash.h"\nnamespace gui {\n')
    f.write('const int kLogoW = %d, kLogoH = %d;\n' % (w, h))
    f.write('const unsigned char kLogo[%d] = {\n' % (w * h))
    for i in range(0, len(px), 32):
        f.write(','.join(str(b) for b in px[i:i + 32]) + ',\n')
    f.write('};\n}\n')
print(w, h, len(px))
